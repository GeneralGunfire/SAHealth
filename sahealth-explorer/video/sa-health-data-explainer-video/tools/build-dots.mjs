// Dot-matrix map of South Africa: grid points inside each province (d3 geoContains).
import fs from 'node:fs';
import {geoMercator, geoContains, geoArea} from 'd3-geo';
const gj = JSON.parse(fs.readFileSync('public/data/za_adm1.geojson', 'utf8'));
const fix = {'Nothern Cape': 'Northern Cape'};
for (const f of gj.features) if (geoArea(f) > 2 * Math.PI) {
  const g = f.geometry, rev = (p) => p.map((r) => r.slice().reverse());
  g.coordinates = g.type === 'Polygon' ? rev(g.coordinates) : g.coordinates.map(rev);
}
const W = 1000, H = 860;
const proj = geoMercator().fitExtent([[10, 10], [W - 10, H - 10]], {type: 'Polygon', coordinates: [[[16.4, -34.9], [16.4, -22.1], [33, -22.1], [33, -34.9], [16.4, -34.9]]]});
const step = 13; // px between dots
const pts = [];
for (let y = 0; y < H; y += step) for (let x = (y / step) % 2 ? step / 2 : 0; x < W; x += step) {
  const ll = proj.invert([x, y]);
  for (const f of gj.features) {
    if (geoContains(f, ll)) { pts.push([Math.round(x), Math.round(y), (fix[f.properties.shapeName] ?? f.properties.shapeName)]); break; }
  }
}
const names = [...new Set(pts.map((p) => p[2]))];
const out = pts.map((p) => [p[0], p[1], names.indexOf(p[2])]);
fs.writeFileSync('src/data/sadots.ts', `// Generated by tools/build-dots.mjs (geoBoundaries ZAF ADM1). [x, y, provinceIndex] in a ${W}x${H} box.\nexport const DOT_W = ${W};\nexport const DOT_H = ${H};\nexport const DOT_PROV: string[] = ${JSON.stringify(names)};\nexport const DOTS: [number, number, number][] = ${JSON.stringify(out)};\n`);
console.log(pts.length, 'dots', names.map((n) => n + ':' + pts.filter((p) => p[2] === n).length).join(' '));
