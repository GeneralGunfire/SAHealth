// Projects geoBoundaries ADM1 (public/data/za_adm1.geojson) into SVG paths for a 1000x860 box.
import fs from 'node:fs';
import {geoMercator, geoPath} from 'd3-geo';
const gj = JSON.parse(fs.readFileSync('public/data/za_adm1.geojson', 'utf8'));
const fix = {'Nothern Cape': 'Northern Cape'};
// geoBoundaries rings are clockwise-agnostic; d3 needs spherical winding — rewind by reversing if area is huge.
import {geoArea} from 'd3-geo';
for (const f of gj.features) {
  if (geoArea(f) > 2 * Math.PI) {
    const g = f.geometry;
    const rev = (poly) => poly.map((r) => r.slice().reverse());
    g.coordinates = g.type === 'Polygon' ? rev(g.coordinates) : g.coordinates.map(rev);
  }
}
const W = 1000, H = 860;
// Exclude Prince Edward Islands (far south-east) from the fit
const proj = geoMercator().fitExtent([[10, 10], [W - 10, H - 10]], {type: 'Polygon', coordinates: [[[16.4, -34.9], [33, -34.9], [33, -22.1], [16.4, -22.1], [16.4, -34.9]]].map(r=>r.reverse())});
const path = geoPath(proj).digits(1);
const out = gj.features.map((f) => {
  const name = fix[f.properties.shapeName] ?? f.properties.shapeName;
  // drop tiny far-off islands
  let g = f.geometry;
  if (g.type === 'MultiPolygon') g = {...g, coordinates: g.coordinates.filter((p) => p[0][0][0] < 34 && p[0][0][1] > -40)};
  const c = path.centroid(g);
  return {name, d: path(g), cx: +c[0].toFixed(1), cy: +c[1].toFixed(1)};
});
fs.writeFileSync('src/data/provinces.ts',
  `// Generated by tools/build-map.mjs from geoBoundaries gbOpen ZAF ADM1 (CC BY 4.0)\nexport const MAP_W = ${W};\nexport const MAP_H = ${H};\nexport const PROVINCES: {name: string; d: string; cx: number; cy: number}[] = ${JSON.stringify(out)};\n`);
console.log(out.map((o) => `${o.name} ${o.d.length} (${o.cx},${o.cy})`).join('\n'));
